def _lesson_task_codes(lesson_code: str) -> tuple[str, ...]:
    return tuple(task.code for task in STAGE_TWO_TASKS if task.lesson_code == lesson_code)


def _lesson_dialogue_codes(lesson_code: str, choice_task_number: int) -> tuple[str, ...]:
    codes = [f"{lesson_code}-В"]
    tasks_by_code = {task.code: task for task in STAGE_TWO_TASKS}
    for number in range(1, 5):
        if number == choice_task_number:
            codes.append(f"{lesson_code}-О")
        task_code = f"{lesson_code}-{number:02d}"
        codes.append(f"{task_code}-ОБУЧЕНИЕ")
        if tasks_by_code[task_code].consequence:
            codes.append(f"{task_code}-ПОСЛЕДСТВИЕ")
    return tuple(codes)


