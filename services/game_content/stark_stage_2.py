def _next_after_task(code: str, consequence: str) -> str:
    if consequence:
        return f"{code}-ПОСЛЕДСТВИЕ"
    lesson_code, number_text = code.rsplit("-", 1)
    next_number = int(number_text) + 1
    if next_number == _CHOICE_TASK_NUMBERS[lesson_code]:
        return f"{lesson_code}-О"
    return f"{lesson_code}-{next_number:02d}-ОБУЧЕНИЕ"


def _task(
    *,
    code: str,
    subject: str,
    lesson_code: str,
    number: int,
    prompt: str,
    input_schema: dict[str, Any],
    answer_key: dict[str, Any],
    hints: tuple[str, str, str, str, str],
    solution: str,
    title: str,
    learning: str,
    consequence: str,
) -> StageTask:
    return StageTask(
        code=code,
        stage=2,
        subject=subject,
        lesson_code=lesson_code,
        number=number,
        prompt=prompt,
        input_schema=input_schema,
        answer_key=answer_key,
        hints=_hints(*hints),
        solution=solution,
        book_card_id=f"{code}-КНИЖКА",
        consequence=consequence,
        mini_learning=learning,
        validation_rules=(
            "Проверяются вычисления, результат и требуемое решение. "
            "Математически равносильные записи допустимы."
        ),
        source_hint=hints[0],
        next_node_code=_next_after_task(code, consequence),
        solution_revealed_requires_equivalent_variant=False,
    )


