def _items(
    node_code: str,
    entries: tuple[tuple[str, str], ...],
    next_code: str,
) -> tuple[dict[str, str], ...]:
    return tuple(
        {
            "code": f"{node_code}-{index}",
            "text": text,
            "response": response,
            "next_code": next_code,
        }
        for index, (text, response) in enumerate(entries, 1)
    )


def _build_lesson_nodes() -> tuple[StageDialogueNode, ...]:
    nodes: list[StageDialogueNode] = []
    tasks_by_code = {task.code: task for task in STAGE_TWO_TASKS}
    for (
        lesson_code, _subject, _number, _title, prerequisites, opening,
        continue_label, choice_task_number, questions, choices,
    ) in _LESSON_DATA:
        menu_code = f"{lesson_code}-В"
        first_learning_code = f"{lesson_code}-01-ОБУЧЕНИЕ"
        nodes.append(StageDialogueNode(
            code=menu_code,
            mode="questions",
            lines=(opening,),
            questions=_items(menu_code, questions, menu_code),
            continue_label=continue_label,
            lesson_code=lesson_code,
            phase="entry",
            required_lesson_codes=prerequisites,
            next_code=first_learning_code,
        ))

        for task_number in range(1, 5):
            task_code = f"{lesson_code}-{task_number:02d}"
            task = tasks_by_code[task_code]
            previous_tasks = tuple(
                f"{lesson_code}-{number:02d}"
                for number in range(1, task_number)
            )
            completed_tasks = (*previous_tasks, task_code)

            if task_number == choice_task_number:
                choice_code = f"{lesson_code}-О"
                learning_code = f"{task_code}-ОБУЧЕНИЕ"
                nodes.append(StageDialogueNode(
                    code=choice_code,
                    mode="choice",
                    lines=(),
                    choices=_items(choice_code, choices, learning_code),
                    lesson_code=lesson_code,
                    task_code=task_code,
                    phase="scene",
                    required_task_codes=previous_tasks,
                    required_lesson_codes=prerequisites,
                    next_code=learning_code,
                ))

            nodes.append(StageDialogueNode(
                code=f"{task_code}-ОБУЧЕНИЕ",
                mode="continue",
                lines=(task.mini_learning,),
                lesson_code=lesson_code,
                task_code=task_code,
                phase="mini_learning",
                required_task_codes=previous_tasks,
                required_lesson_codes=prerequisites,
                next_code=task_code,
                book_card_id=task.book_card_id,
            ))

            if not task.consequence:
                continue
            if task_number == 4:
                next_code = "stage_hub"
                phase = "completion"
            else:
                next_number = task_number + 1
                next_code = (
                    f"{lesson_code}-О"
                    if next_number == choice_task_number
                    else f"{lesson_code}-{next_number:02d}-ОБУЧЕНИЕ"
                )
                phase = "consequence"
            nodes.append(StageDialogueNode(
                code=f"{task_code}-ПОСЛЕДСТВИЕ",
                mode="continue",
                lines=(task.consequence,),
                lesson_code=lesson_code,
                task_code=task_code,
                phase=phase,
                required_task_codes=completed_tasks,
                required_lesson_codes=prerequisites,
                next_code=next_code,
            ))
    return tuple(nodes)


