def _schema(**properties: Any) -> dict[str, Any]:
    return {
        "type": "object",
        "required": tuple(properties),
        "properties": {
            name: {"type": value}
            for name, value in properties.items()
        },
    }


def _hints(*texts: str) -> tuple[Hint, ...]:
    if len(texts) != 5 or len(set(texts)) != 5:
        raise ValueError("Every Stark task needs five distinct hints")
    return tuple(Hint(level=index, text=text) for index, text in enumerate(texts, 1))


