def _build_lesson_nodes() -> tuple[StageDialogueNode, ...]:
    nodes: list[StageDialogueNode] = []
    tasks_by_code = {task.code: task for task in STAGE_THREE_TASKS}
    for lesson_code, _subject, _number, _title, prerequisites, opening, label in _LESSON_DATA:
        nodes.append(StageDialogueNode(
            code=f"{lesson_code}-В",
            mode="questions",
            lines=(opening,),
            questions=(
                {"code": f"{lesson_code}-В-1", "text": "«Что проверяем первым?»", "response": "АСТРА: «Сначала считаем базовое правило, затем усложняем».", "next_code": f"{lesson_code}-В"},
                {"code": f"{lesson_code}-В-2", "text": "«Можно пропустить расчёт?»", "response": "СТАРК: «Производство без расчёта быстро станет аварией».", "next_code": f"{lesson_code}-В"},
                {"code": f"{lesson_code}-В-3", "text": "«Это уже запуск?»", "response": "АСТРА: «Это учебный запуск узла под контролем».", "next_code": f"{lesson_code}-В"},
            ),
            continue_label=label,
            lesson_code=lesson_code,
            phase="entry",
            required_lesson_codes=prerequisites,
            next_code=f"{lesson_code}-01-ОБУЧЕНИЕ",
        ))
        for number in range(1, 5):
            task_code = f"{lesson_code}-{number:02d}"
            task = tasks_by_code[task_code]
            previous = tuple(f"{lesson_code}-{index:02d}" for index in range(1, number))
            completed = (*previous, task_code)
            nodes.append(StageDialogueNode(
                code=f"{task_code}-ОБУЧЕНИЕ",
                mode="continue",
                lines=(task.mini_learning,),
                lesson_code=lesson_code,
                task_code=task_code,
                phase="mini_learning",
                required_task_codes=previous,
                required_lesson_codes=prerequisites,
                next_code=task_code,
                book_card_id=task.book_card_id,
            ))
            nodes.append(StageDialogueNode(
                code=f"{task_code}-ПОСЛЕДСТВИЕ",
                mode="continue",
                lines=(task.consequence,),
                lesson_code=lesson_code,
                task_code=task_code,
                phase="completion" if number == 4 else "consequence",
                required_task_codes=completed if number < 4 else tuple(f"{lesson_code}-{index:02d}" for index in range(1, 5)),
                required_lesson_codes=prerequisites,
                next_code="stage_hub" if number == 4 else f"{lesson_code}-{number + 1:02d}-ОБУЧЕНИЕ",
            ))
    return tuple(nodes)


STAGE_THREE_DIALOGUE_NODES = _build_lesson_nodes()
