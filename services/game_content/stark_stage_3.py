def _schema() -> dict[str, Any]:
    return {
        "type": "object",
        "required": ("answer",),
        "properties": {"answer": {"type": "string"}},
    }


def _hints(code: str, answer: str) -> tuple[Hint, ...]:
    return (
        Hint(level=1, text="Выпиши данные из условия и найди нужное правило."),
        Hint(level=2, text=f"Для {code} сначала посчитай промежуточный результат."),
        Hint(level=3, text="Проверь единицы измерения и порядок действий."),
        Hint(level=4, text="Сравни полученное число с ограничением в задаче."),
        Hint(level=5, text=f"Полное решение: {answer}"),
    )


def _task(
    code: str,
    subject: str,
    lesson_code: str,
    number: int,
    title: str,
    prompt: str,
    answer: str,
    learning: str,
    consequence: str,
) -> StageTask:
    return StageTask(
        code=code,
        stage=3,
        subject=subject,
        lesson_code=lesson_code,
        number=number,
        prompt=prompt,
        input_schema=_schema(),
        answer_key={"answer": answer},
        hints=_hints(code, answer),
        solution=answer,
        book_card_id=f"{code}-КНИЖКА",
        consequence=consequence,
        mini_learning=learning,
        validation_rules="Проверяется итоговый расчёт и смысловое решение.",
        source_hint="Сверь вычисления с условием задачи.",
        next_node_code=f"{code}-ПОСЛЕДСТВИЕ",
        solution_revealed_requires_equivalent_variant=False,
    )


