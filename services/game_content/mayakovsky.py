
from __future__ import annotations

from dataclasses import dataclass
from typing import Any

from .models import BookCard, DialogueNode, Hint, Lesson, Task


@dataclass(frozen=True)
class MayakovskyDialogueNode(DialogueNode):
    lesson_code: str = ""
    task_code: str = ""
    phase: str = ""
    required_task_codes: tuple[str, ...] = ()
    required_lesson_codes: tuple[str, ...] = ()
    next_code: str = ""
    book_card_id: str = ""

    def __post_init__(self) -> None:
        super().__post_init__()
        object.__setattr__(self, "required_task_codes", tuple(self.required_task_codes))
        object.__setattr__(self, "required_lesson_codes", tuple(self.required_lesson_codes))


@dataclass(frozen=True)
class MayakovskyTask(Task):
    mini_learning: str = ""
    validation_rules: str = ""
    source_hint: str = ""
    next_node_code: str = ""
    solution_revealed_requires_equivalent_variant: bool = False
    equivalent_variant_codes: tuple[str, ...] = ()


def _hints(texts: tuple[str, str, str, str, str]) -> tuple[Hint, ...]:
    return tuple(Hint(level=index, text=text, hidden=True) for index, text in enumerate(texts, 1))


def _schema() -> dict[str, Any]:
    return {
        "type": "object",
        "properties": {
            "answer": {
                "type": "string",
                "minLength": 1,
                "description": "Ответ ученика. Для составного ответа части можно разделить точкой с запятой.",
            },
        },
        "required": ["answer"],
        "additionalProperties": False,
    }


def _next_after_task(code: str) -> str:
    lesson_code, number_text = code.rsplit("-", 1)
    number = int(number_text)
    if number == 4:
        return f"{code}-ПОСЛЕДСТВИЕ"
    return f"{lesson_code}-{number + 1:02d}-ОБУЧЕНИЕ"


def _task(
    *,
    code: str,
    stage: int,
    subject: str,
    lesson_code: str,
    number: int,
    prompt: str,
    answer: str,
    hints: tuple[str, str, str, str, str],
    solution: str,
    learning: str,
    consequence: str,
) -> MayakovskyTask:
    return MayakovskyTask(
        code=code,
        stage=stage,
        subject=subject,
        lesson_code=lesson_code,
        number=number,
        prompt=prompt,
        input_schema=_schema(),
        answer_key={"answer": answer},
        hints=_hints(hints),
        solution=solution,
        book_card_id=f"{code}-КНИЖКА",
        consequence=consequence,
        mini_learning=learning,
        validation_rules="Проверяется поле answer; для составных ответов допустима та же смысловая запись, если UI нормализует её до ключа.",
        source_hint=hints[0],
        next_node_code=_next_after_task(code),
    )


