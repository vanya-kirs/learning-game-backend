def _question_items(node_code: str, entries: tuple[tuple[str, str], ...]) -> tuple[dict[str, str], ...]:
    return tuple(
        {"code": f"{node_code}-{index}", "text": text, "response": response, "next_code": node_code}
        for index, (text, response) in enumerate(entries, 1)
    )


def _build_dialogue_nodes() -> tuple[MayakovskyDialogueNode, ...]:
    nodes: list[MayakovskyDialogueNode] = []
    task_map = {task.code: task for task in MAYAKOVSKY_TASKS}
    for code, stage, _subject, _number, _title, prerequisites, intro, questions in _LESSON_DATA:
        lesson_task_codes = _lesson_task_codes(code)
        entry_code = f"{code}-В"
        nodes.append(MayakovskyDialogueNode(
            code=entry_code,
            mode="questions",
            lines=(intro,),
            questions=_question_items(entry_code, questions),
            continue_label="Перейти к проверке",
            lesson_code=code,
            phase="entry",
            required_lesson_codes=prerequisites,
            next_code=f"{lesson_task_codes[0]}-ОБУЧЕНИЕ",
        ))
        for index, task_code in enumerate(lesson_task_codes, 1):
            task = task_map[task_code]
            previous_tasks = tuple(lesson_task_codes[: index - 1])
            completed_tasks = (*previous_tasks, task_code)
            nodes.append(MayakovskyDialogueNode(
                code=f"{task_code}-ОБУЧЕНИЕ",
                mode="continue",
                lines=(task.mini_learning,),
                lesson_code=code,
                task_code=task_code,
                phase="mini_learning",
                required_task_codes=previous_tasks,
                required_lesson_codes=prerequisites,
                next_code=task_code,
                book_card_id=task.book_card_id,
            ))
            if task.consequence:
                next_code = "stage_hub" if index == 4 else f"{lesson_task_codes[index]}-ОБУЧЕНИЕ"
                nodes.append(MayakovskyDialogueNode(
                    code=f"{task_code}-ПОСЛЕДСТВИЕ",
                    mode="continue",
                    lines=(task.consequence,),
                    lesson_code=code,
                    task_code=task_code,
                    phase="completion" if index == 4 else "consequence",
                    required_task_codes=completed_tasks if index == 4 else (task_code,),
                    required_lesson_codes=prerequisites,
                    next_code=next_code,
                ))
    return tuple(nodes)


MAYAKOVSKY_DIALOGUE_NODES = _build_dialogue_nodes()
