def _schema() -> dict[str, Any]:
    return {
        "type": "object",
        "required": ("answer",),
        "properties": {"answer": {"type": "string"}},
    }


def _hints(code: str, answer: str) -> tuple[Hint, ...]:
    return (
        Hint(level=1, text="Определи, какие величины нужно сложить или сравнить."),
        Hint(level=2, text=f"Для {code} проверь ограничение из условия."),
        Hint(level=3, text="Не выбирай вариант, пока не проверены все обязательные условия."),
        Hint(level=4, text="Сформулируй итог: подходит, не подходит или нужно остановиться."),
        Hint(level=5, text=f"Полное решение: {answer}"),
    )


def _task(
    code: str,
    subject: str,
    lesson_code: str,
    number: int,
    title: str,
    prompt: str,
    answer: str,
    learning: str,
    consequence: str,
) -> StageTask:
    return StageTask(
        code=code,
        stage=4,
        subject=subject,
        lesson_code=lesson_code,
        number=number,
        prompt=prompt,
        input_schema=_schema(),
        answer_key={"answer": answer},
        hints=_hints(code, answer),
        solution=answer,
        book_card_id=f"{code}-КНИЖКА",
        consequence=consequence,
        mini_learning=learning,
        validation_rules="Проверяется расчёт и итоговое решение по ограничению.",
        source_hint="Сначала посчитай величину, затем сравни с пределом.",
        next_node_code=f"{code}-ПОСЛЕДСТВИЕ",
        solution_revealed_requires_equivalent_variant=False,
    )


