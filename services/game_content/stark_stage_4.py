def _lesson_task_codes(lesson_code: str) -> tuple[str, ...]:
    return tuple(task.code for task in STAGE_FOUR_TASKS if task.lesson_code == lesson_code)


def _lesson_dialogue_codes(lesson_code: str) -> tuple[str, ...]:
    codes: list[str] = [f"{lesson_code}-В"]
    for number in range(1, 5):
        code = f"{lesson_code}-{number:02d}"
        codes.extend((f"{code}-ОБУЧЕНИЕ", f"{code}-ПОСЛЕДСТВИЕ"))
    return tuple(codes)


